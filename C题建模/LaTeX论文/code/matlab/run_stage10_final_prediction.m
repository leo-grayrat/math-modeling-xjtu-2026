function run_stage10_final_prediction(seed, runMode)
% 阶段10：用冻结路线完成全量训练和正式测试预测。

arguments
    seed (1, 1) double {mustBeInteger, mustBeNonnegative} = 42
    runMode (1, 1) string {mustBeMember(runMode, ...
        ["smoke", "full"])} = "full"
end

rng(seed, "twister");
matlabDir = fileparts(mfilename("fullpath"));
projectDir = fileparts(matlabDir);
repoRoot = fileparts(projectDir);
resultsDir = fullfile(projectDir, "results");
data = stage10_prepare_full_data(repoRoot, projectDir);

trainingRows = true(height(data.labels), 1);
predictionRows = (1:height(data.submission))';
outputPrefix = "stage10";
if runMode == "smoke"
    trainingCells = find(data.cellTrainingMask, 60, "first");
    trainingGenes = find(data.geneTrainingMask, 80, "first");
    trainingRows = ismember(data.rowCellIndex, trainingCells) & ...
        ismember(data.rowGeneIndex, trainingGenes);
    predictionRows = (1:min(500, height(data.submission)))';
    outputPrefix = "stage10_smoke";
end

[baseByGene, baseInfo] = stage7_fit_fold_gene_base( ...
    data.baseGeneFeatures, data.rowGeneIndex(trainingRows), ...
    data.labels.label(trainingRows), seed + 1000);
baseByRow = baseByGene(data.rowGeneIndex);
trainingResidual = data.labels.label(trainingRows) - baseByRow(trainingRows);
model = stage7_fit_two_step_kernel(data.cellKernel, data.geneKernel, ...
    data.rowCellIndex(trainingRows), data.rowGeneIndex(trainingRows), ...
    trainingResidual, 0.1);
linearIndex = sub2ind(size(model.predictionMatrix), ...
    data.submissionCellIndex(predictionRows), ...
    data.submissionGeneIndex(predictionRows));
prediction = baseByGene(data.submissionGeneIndex(predictionRows)) + ...
    model.predictionMatrix(linearIndex);
assert(all(isfinite(prediction)), "stage10:FinitePrediction", ...
    "正式预测中出现 NaN 或 Inf。");

output = data.submission(predictionRows, ...
    ["cell_line_id", "perturbation_gene", "label"]);
output.label = prediction;
if runMode == "full"
    assert(height(output) == height(data.submission), ...
        "stage10:SubmissionRows", "正式预测行数与模板不一致。");
    assert(isequal(output.cell_line_id, data.submission.cell_line_id) && ...
        isequal(output.perturbation_gene, data.submission.perturbation_gene), ...
        "stage10:SubmissionOrder", "正式预测对象顺序与模板不一致。");
end

outputDir = fullfile(resultsDir, "final_submission");
if ~isfolder(outputDir)
    mkdir(outputDir);
end
outputFile = fullfile(outputDir, outputPrefix + "_submission_gene.csv");
writetable(output, outputFile);

summary = table(sum(trainingRows), numel(unique(data.rowCellIndex(trainingRows))), ...
    numel(unique(data.rowGeneIndex(trainingRows))), height(output), ...
    numel(unique(output.cell_line_id)), numel(unique(output.perturbation_gene)), ...
    min(prediction), max(prediction), mean(prediction), std(prediction), ...
    sum(~isfinite(prediction)), baseInfo.lambda, 0.1, ...
    'VariableNames', {'training_rows','training_cells','training_genes', ...
    'prediction_rows','prediction_cells','prediction_genes', ...
    'prediction_min','prediction_max','prediction_mean','prediction_std', ...
    'nonfinite_predictions','base_lambda','kernel_lambda'});
writetable(summary, fullfile(resultsDir, outputPrefix + "_summary.csv"));
fprintf("阶段10%s完成：训练 %d 行，预测 %d 行。\n", ...
    runMode, sum(trainingRows), height(output));
end
